"""Real, human-approved LOCAL staging release for Night Shift.

Distinct from app.approval.simulate_deploy, which records a simulated
deployment only. This module actually runs the approved artifact snapshot
in a separate disposable environment on 127.0.0.1.

Gates before any process starts (all fail closed):
  - incident exists and carries a human approval record
  - incident status is human_approved (approval bound to THIS incident)
  - no staging process is already running for this incident
  - the approved version is not the affected fault-injection version 3.1.2
  - approval binding matches the incident's verified patch (package,
    version, artifact_sha256, manifest)
  - deterministic execution-evidence checks recompute as passing
  - the on-disk artifact manifest recomputes to the verified manifest

The staging environment is built only from the artifact snapshot's own
requirements file (application pins only; pytest is never shipped). The
server process runs a fixed trusted script with fixed arguments, binds
127.0.0.1 only, and is validated via /health and /smoke before the release
is recorded. Any failure — malformed response, wrong versions, startup
error, timeout — kills the process and removes the staging directory.

Popen objects live in a module-level registry keyed by incident id; they
are never placed in incident records, which stay JSON-serializable.
"""
import json
import shutil
import socket
import subprocess
import tempfile
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Optional

from app.isolated_runner import (
    FAULT_INJECTION_VERSION,
    REMEDIATION_PACKAGE,
    recompute_manifest,
    manifest_matches,
)
from app import evidence as evidence_mod

STAGING_ROOT = Path(__file__).resolve().parent.parent / "staging"

HEALTH_TIMEOUT_S = 5.0
STARTUP_TIMEOUT_S = 60.0
STOP_TIMEOUT_S = 10.0

EXPECTED_SUPPORTING = {"MarkupSafe": "2.1.5"}

# Registry of live staging processes, keyed by incident id. Never serialized.
_processes: dict = {}
# Registry of staging directories for running releases.
_staging_dirs: dict = {}


def _ts() -> str:
    return datetime.now(timezone.utc).isoformat()


# --------------------------------------------------------------------------
# Injectable environment/startup layer (mock tests replace these).
# --------------------------------------------------------------------------

def _run(cmd: list, cwd: Optional[Path] = None, timeout: float = 300.0):
    try:
        proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True,
                              timeout=timeout)
        return proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired:
        return None, "", f"command timed out after {timeout}s"


def _make_env(staging_dir: Path, requirements_path: Path) -> Optional[str]:
    """Create a disposable venv and install the artifact's requirements.

    Returns the venv python path, or None on failure.
    """
    venv_dir = staging_dir / "venv"
    rc, out, err = _run(["python3", "-m", "venv", str(venv_dir)])
    if rc != 0:
        return None
    pip = venv_dir / "bin" / "pip"
    rc, out, err = _run([str(pip), "install", "-q", "-r", str(requirements_path)])
    if rc != 0:
        return None
    return str(venv_dir / "bin" / "python")


def _start(cmd: list, cwd: Path, log_path: Path):
    """Start the staging server process; returns a Popen-like object."""
    log_file = open(log_path, "ab")
    try:
        return subprocess.Popen(cmd, cwd=cwd, stdout=log_file, stderr=log_file)
    except Exception:
        log_file.close()
        raise


def _get_json(url: str, timeout: float = HEALTH_TIMEOUT_S) -> dict:
    """Fetch and parse JSON. Raises on any transport or parse failure."""
    with urllib.request.urlopen(url, timeout=timeout) as resp:
        body = resp.read().decode("utf-8", errors="replace")
    return json.loads(body)


# --------------------------------------------------------------------------
# Fixed trusted server script content (never model- or request-controlled).
# --------------------------------------------------------------------------

_SERVER_PY = '''\
"""Trusted Night Shift staging server (fixed content, generated by the
release orchestrator). Serves /health and /smoke for the approved snapshot.

Bound to 127.0.0.1 only. Application dependencies only (no pytest).
"""
import json
import sys
from http.server import BaseHTTPRequestHandler, HTTPServer
from importlib.metadata import version as pkg_version

sys.path.insert(0, ".")

import main as app_main  # the approved artifact snapshot's application


class Handler(BaseHTTPRequestHandler):
    def _send(self, code, payload):
        body = json.dumps(payload).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if self.path == "/health":
            self._send(200, {
                "status": "ok",
                "jinja2": pkg_version("jinja2"),
                "MarkupSafe": pkg_version("MarkupSafe"),
            })
        elif self.path == "/smoke":
            checks = {}
            # XSS escaping smoke.
            out = app_main.render_greeting("<script>x</script>")
            checks["greeting_escapes_html"] = "<script>" not in out
            # CVE-2024-22195: space in attribute key must raise.
            try:
                app_main.render_attrs({"class": "ok", "onclick alert": "x"})
                checks["xmlattr_rejects_space"] = False
            except ValueError:
                checks["xmlattr_rejects_space"] = True
            # CVE-2024-34064: slash in attribute key must raise.
            try:
                app_main.render_attrs({"class": "ok", "onclick/x": "x"})
                checks["xmlattr_rejects_slash"] = False
            except ValueError:
                checks["xmlattr_rejects_slash"] = True
            ok = all(checks.values())
            self._send(200, {"status": "ok" if ok else "failed", "checks": checks})
        else:
            self._send(404, {"error": "not found"})

    def log_message(self, fmt, *args):
        pass  # keep stdout quiet; the orchestrator logs to file


if __name__ == "__main__":
    port = int(sys.argv[1])
    HTTPServer(("127.0.0.1", port), Handler).serve_forever()
'''


# --------------------------------------------------------------------------
# Gate helpers
# --------------------------------------------------------------------------

def _release_gate(incident: dict) -> Optional[str]:
    """All checks that must pass before any staging work begins."""
    if not incident:
        return "No incident provided."
    if incident.get("staging_release", {}).get("running"):
        return "A staging process is already running for this incident."
    if incident.get("staging_release", {}).get("released"):
        return "This incident already has a recorded staging release."
    approval = incident.get("human_approval")
    if not approval or not approval.get("approved"):
        return "Staging release requires explicit human approval first."
    if incident.get("status") != "human_approved":
        return (f"Incident status is {incident.get('status')!r}; "
                "staging release requires human_approved.")

    bound = incident.get("verified_patch") or {}
    # The affected fault-injection version can NEVER be released, even if a
    # forged approval record claims otherwise.
    if (bound.get("version") == FAULT_INJECTION_VERSION
            or approval.get("patch", {}).get("version") == FAULT_INJECTION_VERSION):
        return (f"The affected version {FAULT_INJECTION_VERSION} "
                "(fault injection) can never be released to staging.")

    # Approval binding must match the incident's verified patch exactly.
    if (approval.get("patch", {}).get("package") != bound.get("package")
            or approval.get("patch", {}).get("version") != bound.get("version")
            or approval.get("artifact_sha256") != bound.get("artifact_sha256")):
        return ("Approval binding does not match the incident's verified "
                "patch (package/version/artifact hash).")

    # Recompute execution-evidence checks at the release boundary.
    verified_attempt = None
    for attempt in reversed(incident.get("attempts", [])):
        if attempt.get("qa", {}).get("approval") is True:
            verified_attempt = attempt
            break
    if not verified_attempt:
        return "No QA-approved attempt found."
    failed = evidence_mod.failed_check_names(verified_attempt.get("verification", {}))
    if failed:
        return f"Recomputed evidence checks failed at release time: {failed}"

    # Artifact manifest recompute from actual bytes on disk.
    reason = manifest_matches(recompute_manifest(bound.get("artifact_dir")),
                              bound.get("manifest"))
    if reason:
        return f"Artifact manifest recheck failed: {reason}"

    return None


def _health_gate(payload: Any, expected_version: str) -> Optional[str]:
    """Validate /health JSON. Fail closed on anything malformed or wrong."""
    if not isinstance(payload, dict):
        return f"health response is not a JSON object: {payload!r}"
    if payload.get("status") != "ok":
        return f"health status is {payload.get('status')!r}, expected 'ok'"
    if payload.get("jinja2") != expected_version:
        return (f"health reports jinja2 {payload.get('jinja2')!r}, "
                f"expected the approved pin {expected_version}")
    for dep, expected in EXPECTED_SUPPORTING.items():
        if payload.get(dep) != expected:
            return (f"health reports {dep} {payload.get(dep)!r}, "
                    f"expected the approved pin {expected}")
    return None


def _smoke_gate(payload: Any) -> Optional[str]:
    if not isinstance(payload, dict):
        return f"smoke response is not a JSON object: {payload!r}"
    if payload.get("status") != "ok":
        return f"smoke status is {payload.get('status')!r}: {payload.get('checks')}"
    return None


# --------------------------------------------------------------------------
# Staging lifecycle
# --------------------------------------------------------------------------

def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def release(incident: dict, port: Optional[int] = None,
            staging_root: Optional[Path] = None) -> dict:
    """Release the human-approved artifact snapshot to local staging.

    Runs the snapshot in a separate venv on 127.0.0.1 with fixed trusted
    commands, validates health and smoke, and records the release. On any
    failure the process is stopped and the staging directory is removed.
    """
    gate = _release_gate(incident)
    if gate:
        result = {"released": False, "error": gate,
                  "incident_id": incident.get("id") if incident else None,
                  "utc_timestamp": _ts()}
        if incident:
            incident["events"].append({"agent": "staging",
                                       "action": "release_failed", **result})
        return result

    incident_id = incident["id"]
    bound = incident["verified_patch"]
    version = bound["version"]
    artifact_dir = Path(bound["artifact_dir"])

    root = Path(staging_root) if staging_root else STAGING_ROOT
    staging_dir = root / incident_id
    process = None
    started = False

    def _fail(reason: str, cleanup: bool = True) -> dict:
        nonlocal process
        if process is not None:
            _kill(process)
        _processes.pop(incident_id, None)
        _staging_dirs.pop(incident_id, None)
        if cleanup and staging_dir.exists():
            shutil.rmtree(staging_dir, ignore_errors=True)
        result = {"released": False, "error": reason, "incident_id": incident_id,
                  "utc_timestamp": _ts()}
        incident["events"].append({"agent": "staging", "action": "release_failed",
                                   **result})
        return result

    try:
        # Fresh staging directory built ONLY from the artifact snapshot.
        if staging_dir.exists():
            shutil.rmtree(staging_dir)
        staging_dir.mkdir(parents=True)

        # Re-check the manifest immediately before copying (TOCTOU shrink).
        reason = manifest_matches(recompute_manifest(artifact_dir), bound.get("manifest"))
        if reason:
            return _fail(f"Artifact manifest recheck failed before copy: {reason}")

        app_dir = staging_dir / "app"
        app_dir.mkdir()
        for name in ("main.py", "test_regression.py", "pytest.ini",
                     "requirements-proposed.txt"):
            src = artifact_dir / name if name.startswith("requirements") \
                else artifact_dir / "app" / name
            shutil.copyfile(src, app_dir / name)
        (app_dir / "server.py").write_text(_SERVER_PY)

        # Separate environment: application pins only, installed from the
        # artifact's own proposed requirements file.
        venv_python = _make_env(staging_dir, app_dir / "requirements-proposed.txt")
        if not venv_python:
            return _fail("staging environment build failed (venv or install)")

        port = int(port) if port else _free_port()
        log_path = staging_dir / "server.log"

        # Fixed trusted command; nothing model- or request-derived in it.
        process = _start([venv_python, "server.py", str(port)], app_dir, log_path)
        _processes[incident_id] = process
        _staging_dirs[incident_id] = staging_dir
        started = True

        # Startup + health validation, then smoke validation.
        base = f"http://127.0.0.1:{port}"
        deadline = time.monotonic() + STARTUP_TIMEOUT_S
        health = None
        while time.monotonic() < deadline:
            if process.poll() is not None:
                return _fail(f"staging server exited during startup "
                             f"(rc={process.returncode}); see server.log")
            try:
                health = _get_json(f"{base}/health")
                break
            except Exception:
                time.sleep(0.5)
        if health is None:
            return _fail(f"staging server did not become healthy within "
                         f"{STARTUP_TIMEOUT_S}s")

        reason = _health_gate(health, version)
        if reason:
            return _fail(f"health validation failed: {reason}")

        try:
            smoke = _get_json(f"{base}/smoke")
        except Exception as exc:
            return _fail(f"smoke check request failed: {exc}")
        reason = _smoke_gate(smoke)
        if reason:
            return _fail(f"smoke validation failed: {reason}")

        record = {
            "released": True,
            "incident_id": incident_id,
            "package": REMEDIATION_PACKAGE,
            "version": version,
            "artifact_sha256": bound.get("artifact_sha256"),
            "manifest_recheck": "passed",
            "port": port,
            "bound_to": "127.0.0.1",
            "health": health,
            "smoke": smoke,
            "running": True,
            "utc_timestamp": _ts(),
            "note": ("Real local staging on 127.0.0.1 from the approved "
                     "artifact snapshot; separate from simulated deployment."),
        }
        incident["staging_release"] = record
        incident["status"] = "staging_released"
        incident["events"].append({"agent": "staging", "action": "release_succeeded",
                                   **record})
        return record

    except Exception as exc:
        if started or process is not None:
            return _fail(f"staging release failed: {exc}")
        return _fail(f"staging release failed: {exc}", cleanup=staging_dir.exists())


def _kill(process) -> None:
    try:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=STOP_TIMEOUT_S)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=STOP_TIMEOUT_S)
    except Exception:
        pass


def stop(incident: dict) -> dict:
    """Stop the running staging process for an incident and clean up."""
    if not incident:
        return {"stopped": False, "error": "No incident provided.",
                "utc_timestamp": _ts()}
    incident_id = incident.get("id")
    process = _processes.get(incident_id)
    record = incident.get("staging_release") or {}
    if process is None and not record.get("running"):
        return {"stopped": False, "error": "No staging process is running for "
                "this incident.", "incident_id": incident_id,
                "utc_timestamp": _ts()}
    if process is not None:
        _kill(process)
        _processes.pop(incident_id, None)
    staging_dir = _staging_dirs.pop(incident_id, None)
    if staging_dir and staging_dir.exists():
        shutil.rmtree(staging_dir, ignore_errors=True)
    if record:
        record["running"] = False
        record["stopped_utc_timestamp"] = _ts()
    incident["events"].append({"agent": "staging", "action": "stop",
                               "incident_id": incident_id,
                               "utc_timestamp": _ts()})
    return {"stopped": True, "incident_id": incident_id,
            "utc_timestamp": _ts()}


def status(incident: dict) -> dict:
    """Report staging state without changing anything."""
    if not incident:
        return {"error": "No incident provided."}
    record = incident.get("staging_release") or {}
    process = _processes.get(incident.get("id"))
    running = bool(process is not None and process.poll() is None)
    return {
        "incident_id": incident.get("id"),
        "released": bool(record.get("released")),
        "running": running and bool(record.get("running")),
        "process_alive": running,
        "port": record.get("port"),
        "version": record.get("version"),
        "utc_timestamp": _ts(),
    }
